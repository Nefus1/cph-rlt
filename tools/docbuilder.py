"""Small DSL for generating the Docassemble DOCX templates with python-docx.

Each template is described as a list of blocks. Paragraph text may contain
Jinja2 (docxtpl) tags and a few inline markup tags:

    <b>bold</b>  <i>italic</i>  <u>underline</u>  <ph>highlighted placeholder</ph>
    <br>  (line break)   <tab>   <field:PAGE>  <field:NUMPAGES>

Inline markup must never be placed *inside* a Jinja tag, so every Jinja tag
ends up inside a single Word run, which is what docxtpl requires.

Numbering uses one Word multilevel list linked to paragraph styles:
    level 0  "ARTICLE ONE"  (style "Heading 1", so a TOC can pick it up)
    level 1  "1.1"          (style "Trust Section")
    level 2  "(a)"          (style "Trust Sub")
    level 3  "(i)"          (style "Trust SubSub")
Because the numbers are generated by Word/LibreOffice, articles and sections
removed by {%p if %} blocks renumber automatically.
"""

import re

from docx import Document
from docx.enum.section import WD_ORIENT
from docx.enum.style import WD_STYLE_TYPE
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_BREAK, WD_COLOR_INDEX
from docx.oxml import parse_xml
from docx.oxml.ns import nsdecls, qn
from docx.shared import Inches, Pt, RGBColor

FONT = 'Times New Roman'
NUM_ID = 77
ABSTRACT_ID = 77

TOKEN = re.compile(r'(</?b>|</?i>|</?u>|</?ph>|<br>|<tab>|<field:[A-Z]+>)')


def _set_font(style_or_run_font, size=12, bold=None, italic=None, caps=None):
    f = style_or_run_font
    f.name = FONT
    f.size = Pt(size)
    if bold is not None:
        f.bold = bold
    if italic is not None:
        f.italic = italic
    if caps is not None:
        f.all_caps = caps
    f.color.rgb = RGBColor(0, 0, 0)


def _east_asia(style):
    rpr = style.element.get_or_add_rPr()
    rfonts = rpr.find(qn('w:rFonts'))
    if rfonts is None:
        rfonts = parse_xml('<w:rFonts %s/>' % nsdecls('w'))
        rpr.insert(0, rfonts)
    for attr in ('w:ascii', 'w:hAnsi', 'w:eastAsia', 'w:cs'):
        rfonts.set(qn(attr), FONT)
    for attr in ('w:asciiTheme', 'w:hAnsiTheme', 'w:eastAsiaTheme', 'w:cstheme'):
        if rfonts.get(qn(attr)) is not None:
            del rfonts.attrib[qn(attr)]


class Builder:
    def __init__(self, numbered=True, line_spacing=1.0, space_after=10):
        self.doc = Document()
        self.numbered = numbered
        sec = self.doc.sections[0]
        sec.orientation = WD_ORIENT.PORTRAIT
        sec.page_width = Inches(8.5)
        sec.page_height = Inches(11)
        for side in ('left_margin', 'right_margin', 'top_margin'):
            setattr(sec, side, Inches(1))
        sec.bottom_margin = Inches(0.9)
        sec.footer_distance = Inches(0.4)
        self._styles(line_spacing, space_after)
        if numbered:
            self._numbering()
        # python-docx starts with one empty paragraph; remove it.
        body = self.doc.element.body
        for p in list(body.iterchildren(qn('w:p'))):
            body.remove(p)

    # ------------------------------------------------------------ styles
    def _styles(self, line_spacing, space_after):
        st = self.doc.styles
        normal = st['Normal']
        _set_font(normal.font)
        _east_asia(normal)
        pf = normal.paragraph_format
        pf.space_before = Pt(0)
        pf.space_after = Pt(space_after)
        pf.line_spacing = line_spacing
        pf.widow_control = True

        def pstyle(name, base='Normal', size=12, bold=None, italic=None, caps=None,
                   align=None, first=None, left=None, hanging=None, before=None,
                   after=None, keep=False):
            try:
                s = st[name]
            except KeyError:
                s = st.add_style(name, WD_STYLE_TYPE.PARAGRAPH)
            s.base_style = st[base] if base and base != name else None
            _set_font(s.font, size, bold, italic, caps)
            _east_asia(s)
            p = s.paragraph_format
            if align is not None:
                p.alignment = align
            if first is not None:
                p.first_line_indent = first
            if left is not None:
                p.left_indent = left
            if hanging is not None:
                p.left_indent = (left or Inches(0)) + hanging
                p.first_line_indent = -hanging
            if before is not None:
                p.space_before = Pt(before)
            if after is not None:
                p.space_after = Pt(after)
            p.keep_with_next = keep
            return s

        J = WD_ALIGN_PARAGRAPH.JUSTIFY
        C = WD_ALIGN_PARAGRAPH.CENTER
        pstyle('Doc Title', size=16, bold=True, caps=True, align=C, after=6, keep=True)
        pstyle('Doc Subtitle', size=12, italic=True, align=C, after=6, keep=True)
        pstyle('Center', align=C)
        pstyle('Center Bold', bold=True, align=C, keep=True)
        pstyle('Heading 1', size=12, bold=True, caps=True, align=C, before=18, after=12, keep=True)
        pstyle('Trust Section', align=J)
        pstyle('Trust Sub', align=J)
        pstyle('Trust SubSub', align=J)
        pstyle('Body', align=J, first=Inches(0.5))
        pstyle('Body Indent', align=J, left=Inches(1.0))
        pstyle('Plain', align=J)
        pstyle('Plain Left', align=WD_ALIGN_PARAGRAPH.LEFT)
        pstyle('Hang', align=J, hanging=Inches(0.5))
        pstyle('Bullet Plain', align=WD_ALIGN_PARAGRAPH.LEFT, hanging=Inches(0.25), left=Inches(0.25), after=4)
        pstyle('Sig Line', align=WD_ALIGN_PARAGRAPH.LEFT, left=Inches(3.0), before=30, after=0, keep=True)
        pstyle('Sig Name', align=WD_ALIGN_PARAGRAPH.LEFT, left=Inches(3.0), after=6, keep=True)
        pstyle('Schedule Title', size=12, bold=True, caps=True, align=C, after=4, keep=True)
        pstyle('Small', size=10, align=J, after=4)
        pstyle('Table Text', size=10, after=0, align=WD_ALIGN_PARAGRAPH.LEFT)
        pstyle('Table Head', size=10, bold=True, after=0, align=WD_ALIGN_PARAGRAPH.LEFT)
        pstyle('Memo Heading', size=13, bold=True, before=12, after=6, keep=True)
        pstyle('Control', size=1)
        footer = st['Footer']
        _set_font(footer.font, size=9)
        _east_asia(footer)
        footer.paragraph_format.space_after = Pt(0)
        contents = pstyle('Contents Line', after=3, left=Inches(1.0))
        contents.paragraph_format.tab_stops.add_tab_stop(Inches(2.6))
        for name in ('TOC 1', 'Contents 1'):
            s = pstyle(name, after=4)
            s.paragraph_format.tab_stops.add_tab_stop(Inches(6.5), alignment=2, leader=1)

    # --------------------------------------------------------- numbering
    def _numbering(self):
        w = nsdecls('w')
        lvls = [
            # ilvl, fmt, text, style, ind, extra
            (0, 'cardinalText', 'Article %1', 'Heading1',
             '<w:ind w:left="0" w:firstLine="0"/>', '<w:suff w:val="nothing"/>', 'center'),
            (1, 'decimal', '%1.%2', 'TrustSection',
             '<w:tabs><w:tab w:val="num" w:pos="1440"/></w:tabs><w:ind w:left="0" w:firstLine="720"/>',
             '<w:isLgl/>', 'left'),
            (2, 'lowerLetter', '(%3)', 'TrustSub',
             '<w:tabs><w:tab w:val="num" w:pos="1440"/></w:tabs><w:ind w:left="1440" w:hanging="720"/>',
             '', 'left'),
            (3, 'lowerRoman', '(%4)', 'TrustSubSub',
             '<w:tabs><w:tab w:val="num" w:pos="2160"/></w:tabs><w:ind w:left="2160" w:hanging="720"/>',
             '', 'left'),
        ]
        parts = []
        for ilvl, fmt, text, style, ind, extra, jc in lvls:
            caps = '<w:rPr><w:b/><w:caps/></w:rPr>' if ilvl == 0 else ''
            # isLgl must precede lvlText; suff follows lvlText.
            is_lgl = extra if extra == '<w:isLgl/>' else ''
            suff = extra if extra.startswith('<w:suff') else ''
            parts.append(
                '<w:lvl w:ilvl="%d"><w:start w:val="1"/><w:numFmt w:val="%s"/>'
                '<w:pStyle w:val="%s"/>%s%s<w:lvlText w:val="%s"/><w:lvlJc w:val="%s"/>'
                '<w:pPr>%s</w:pPr>%s</w:lvl>'
                % (ilvl, fmt, style, is_lgl, suff, text, jc, ind, caps))
        absxml = ('<w:abstractNum %s w:abstractNumId="%d"><w:multiLevelType w:val="multilevel"/>%s'
                  '</w:abstractNum>' % (w, ABSTRACT_ID, ''.join(parts)))
        # Schema order inside <w:lvl>: start, numFmt, lvlRestart, pStyle, isLgl, suff, lvlText, ...
        absxml = absxml.replace('<w:pStyle w:val="Heading1"/><w:suff', '<w:pStyle w:val="Heading1"/><w:suff')
        numbering = self.doc.part.numbering_part.element
        first_num = numbering.find(qn('w:num'))
        node = parse_xml(absxml)
        if first_num is not None:
            first_num.addprevious(node)
        else:
            numbering.append(node)
        numbering.append(parse_xml('<w:num %s w:numId="%d"><w:abstractNumId w:val="%d"/></w:num>'
                                   % (w, NUM_ID, ABSTRACT_ID)))
        st = self.doc.styles
        for ilvl, name in enumerate(['Heading 1', 'Trust Section', 'Trust Sub', 'Trust SubSub']):
            ppr = st[name].element.get_or_add_pPr()
            for old in ppr.findall(qn('w:numPr')):
                ppr.remove(old)
            numpr = parse_xml('<w:numPr %s><w:ilvl w:val="%d"/><w:numId w:val="%d"/></w:numPr>'
                              % (w, ilvl, NUM_ID))
            # numPr must come early in pPr (after keepNext/keepLines/pageBreakBefore etc.)
            anchor = None
            for tag in ('w:spacing', 'w:ind', 'w:jc', 'w:outlineLvl'):
                anchor = ppr.find(qn(tag))
                if anchor is not None:
                    break
            if anchor is not None:
                anchor.addprevious(numpr)
            else:
                ppr.append(numpr)
            # Fix the indents on the styles too, so Word and LibreOffice agree.
            pf = st[name].paragraph_format
            if ilvl == 0:
                pf.left_indent = Inches(0)
                pf.first_line_indent = Inches(0)
            elif ilvl == 1:
                pf.left_indent = Inches(0)
                pf.first_line_indent = Inches(0.5)
            elif ilvl == 2:
                pf.left_indent = Inches(1.0)
                pf.first_line_indent = Inches(-0.5)
            else:
                pf.left_indent = Inches(1.5)
                pf.first_line_indent = Inches(-0.5)
        h1 = st['Heading 1'].element.get_or_add_pPr()
        if h1.find(qn('w:outlineLvl')) is None:
            h1.append(parse_xml('<w:outlineLvl %s w:val="0"/>' % w))

    # ------------------------------------------------------------ inline
    def _runs(self, paragraph, text):
        bold = italic = under = ph = False
        for tok in TOKEN.split(text):
            if not tok:
                continue
            if tok == '<b>':
                bold = True
            elif tok == '</b>':
                bold = False
            elif tok == '<i>':
                italic = True
            elif tok == '</i>':
                italic = False
            elif tok == '<u>':
                under = True
            elif tok == '</u>':
                under = False
            elif tok == '<ph>':
                ph = True
            elif tok == '</ph>':
                ph = False
            elif tok == '<br>':
                paragraph.add_run().add_break(WD_BREAK.LINE)
            elif tok == '<tab>':
                paragraph.add_run('\t')
            elif tok.startswith('<field:'):
                name = tok[7:-1]
                fld = parse_xml('<w:fldSimple %s w:instr=" %s \\* MERGEFORMAT "><w:r><w:t>1</w:t></w:r></w:fldSimple>'
                                % (nsdecls('w'), name))
                paragraph._p.append(fld)
            else:
                run = paragraph.add_run(tok)
                if bold:
                    run.bold = True
                if italic:
                    run.italic = True
                if under:
                    run.underline = True
                if ph:
                    run.bold = True
                    run.font.highlight_color = WD_COLOR_INDEX.YELLOW
        return paragraph

    def para(self, text, style='Normal', keep=None, align=None, before=None, after=None, page_break_before=False):
        p = self.doc.add_paragraph(style=style)
        self._runs(p, text)
        pf = p.paragraph_format
        if keep is not None:
            pf.keep_with_next = keep
        if align is not None:
            pf.alignment = align
        if before is not None:
            pf.space_before = Pt(before)
        if after is not None:
            pf.space_after = Pt(after)
        if page_break_before:
            pf.page_break_before = True
        return p

    # ------------------------------------------------------------ blocks
    def title(self, text):
        return self.para(text, 'Doc Title')

    def subtitle(self, text):
        return self.para(text, 'Doc Subtitle')

    def center(self, text, **kw):
        return self.para(text, 'Center', **kw)

    def article(self, title):
        # Number "ARTICLE ONE" comes from the list; the title follows a line break.
        return self.para('<br>' + title, 'Heading 1')

    def section(self, heading, body=''):
        text = '<b>%s.</b>' % heading if heading else ''
        if body:
            text = (text + '  ' + body) if text else body
        return self.para(text, 'Trust Section')

    def sub(self, text):
        return self.para(text, 'Trust Sub')

    def subsub(self, text):
        return self.para(text, 'Trust SubSub')

    def body(self, text):
        return self.para(text, 'Body')

    def plain(self, text, **kw):
        return self.para(text, 'Plain', **kw)

    def para_left(self, text, **kw):
        return self.para(text, 'Plain Left', **kw)

    def ctl(self, tag):
        """A docxtpl paragraph-level control tag ({%p ... %}); removed at assembly."""
        assert tag.startswith('{%p ') or tag.startswith('{{p '), tag
        return self.para(tag, 'Control', after=0)

    def page_break(self):
        p = self.doc.add_paragraph(style='Normal')
        p.paragraph_format.space_after = Pt(0)
        p.add_run().add_break(WD_BREAK.PAGE)
        return p

    def sig(self, name_line, label=None):
        self.para('_______________________________________', 'Sig Line')
        text = name_line if not label else name_line + '<br>' + label
        return self.para(text, 'Sig Name')

    def table(self, headers, rows, widths=None, loop=None, shade='D9E2F3'):
        """A bordered table. ``rows`` is a list of cell-text lists.

        With ``loop`` = ('for x in xs', ['{{ x.a }}', ...]) a docxtpl row loop is
        produced: {%tr for %} row, the template row, and {%tr endfor %} row.
        """
        ncols = len(headers) if headers else len(rows[0])
        t = self.doc.add_table(rows=0, cols=ncols)
        t.style = self.doc.styles['Table Grid']
        t.alignment = WD_TABLE_ALIGNMENT.CENTER

        def add_row(cells, style='Table Text', header=False):
            r = t.add_row()
            for idx, text in enumerate(cells):
                cell = r.cells[idx]
                cell.paragraphs[0].style = self.doc.styles[style]
                self._runs(cell.paragraphs[0], text)
                if header:
                    tcpr = cell._tc.get_or_add_tcPr()
                    tcpr.append(parse_xml('<w:shd %s w:val="clear" w:color="auto" w:fill="%s"/>'
                                          % (nsdecls('w'), shade)))
            return r

        if headers:
            hdr = add_row(headers, 'Table Head', header=True)
            trpr = hdr._tr.get_or_add_trPr()
            trpr.append(parse_xml('<w:tblHeader %s/>' % nsdecls('w')))
        for row in rows:
            add_row(row)
        if loop:
            add_row(['{%%tr %s %%}' % loop[0]] + [''] * (ncols - 1))
            add_row(loop[1])
            add_row(['{%tr endfor %}'] + [''] * (ncols - 1))
        if widths:
            for r in t.rows:
                for idx, wdt in enumerate(widths):
                    r.cells[idx].width = Inches(wdt)
        # a little space after the table
        sp = self.doc.add_paragraph(style='Normal')
        sp.paragraph_format.space_after = Pt(4)
        return t

    # ------------------------------------------------------------ footer
    def footer(self, left_text, initials=None, center=False):
        """Centered footer: document name on one line, 'Page X of Y' (and an
        optional initials line, which may contain Jinja) on the next."""
        sec = self.doc.sections[0]
        ft = sec.footer
        ft.is_linked_to_previous = False
        p = ft.paragraphs[0]
        p.style = self.doc.styles['Footer']
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        self._runs(p, '<i>' + left_text + '</i>')
        q = ft.add_paragraph(style='Footer')
        q.alignment = WD_ALIGN_PARAGRAPH.CENTER
        self._runs(q, 'Page <field:PAGE> of <field:NUMPAGES>' + (initials or ''))
        return ft

    def save(self, path):
        self.doc.save(path)
